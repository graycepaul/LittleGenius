// Build flat array for quiz use
export const ALL_VOCAB = Object.values(FRENCH_VOCAB).flat()

// Get 3 wrong answers for a word (different from correct)
export function getWrongOptions(correct, count = 3, fromCategory = null) {
  const pool = fromCategory ? FRENCH_VOCAB[fromCategory] : ALL_VOCAB
  const others = pool.filter(w => w.french !== correct.french)
  const shuffled = [...others].sort(() => Math.random() - 0.5)
  return shuffled.slice(0, count)
}

